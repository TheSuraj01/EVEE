"""'Open chrome', 'open YouTube in a new tab' and 'put the PC to sleep' through the real
agent: local matcher, cloud model (faked), policy engine, confirmation, executors."""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from tests.conftest import AlwaysConfirm, FakeTransport, RecordingKeySender, RecordingWindowBackend

from voice_agent.bootstrap import Agent, SystemSeams, build_agent
from voice_agent.core.models import ExecutionStatus, IntentSource
from voice_agent.settings.loader import load_settings

APPS = {
    "Microsoft Stream": "Microsoft.Stream",
    "Google Chrome": "Chrome",
    "Visual Studio Code": "Microsoft.VisualStudioCode",
    "Microsoft Edge": "MSEdge",
    "Notepad": "Microsoft.WindowsNotepad_8wekyb3d8bbwe!App",
    "Notepad++": r"{6D809377}\Notepad++\notepad++.exe",
    "Settings": "windows.immersivecontrolpanel_cw5n1h2txyewy!microsoft.windows.settings",
    "Uninstall Node.js": "Microsoft.AutoGenerated.{BF60}",
}


class Rig:
    def __init__(self, tmp_path: Path, replies: list[dict[str, object]] | None = None) -> None:
        self.launched: list[str] = []
        self.opened: list[str] = []
        self.keys = RecordingKeySender()
        self.prompt = AlwaysConfirm(answer=True)
        self.transport = FakeTransport([json.dumps(_reply(**r)) for r in replies or []])
        self.agent: Agent = build_agent(
            load_settings(env={}),
            keys=self.keys,
            windows=RecordingWindowBackend(),
            prompt=self.prompt,
            audit_path=tmp_path / "audit.jsonl",
            llm=self.transport,
            seams=SystemSeams(
                apps={k: v for k, v in APPS.items() if not k.startswith("Uninstall")},
                launch_app=self.launched.append,
                open_address=self.opened.append,
            ),
        )


def _reply(
    intent: str, text: str | None = None, confidence: float = 0.9, confirm: bool = False
) -> dict[str, object]:
    return {
        "intent": intent,
        "argument_seconds": None,
        "argument_text": text,
        "requires_confirmation": confirm,
        "confidence": confidence,
    }


@pytest.mark.parametrize(
    ("said", "app"),
    [
        ("Open Chrome.", "Chrome"),
        ("open google chrome", "Chrome"),
        ("Launch VS Code.", "Microsoft.VisualStudioCode"),
        ("open vscode", "Microsoft.VisualStudioCode"),
        ("start edge", "MSEdge"),
        ("Open notepad.", "Microsoft.WindowsNotepad_8wekyb3d8bbwe!App"),
        ("open notepad plus plus", r"{6D809377}\Notepad++\notepad++.exe"),
        ("open the chrome app", "Chrome"),
        ("Open crome.", "Chrome"),  # a close mishearing of one app, no other near it
        ("open settings", APPS["Settings"]),
    ],
)
def test_an_installed_app_opens_by_name_with_no_cloud_call(
    tmp_path: Path, said: str, app: str
) -> None:
    rig = Rig(tmp_path)
    assert rig.agent.handle(said).ok
    assert rig.launched == [app]
    assert rig.transport.calls == []  # invariant 3: a known command never needs the network


def test_the_agents_own_open_commands_still_win(tmp_path: Path) -> None:
    """'open task manager' is the desktop command, 'open a new tab' the browser's."""
    rig = Rig(tmp_path)
    rig.agent.handle("open task manager")
    rig.agent.handle("open a new tab")
    assert rig.launched == []
    assert rig.keys.calls == [("ctrl", "shift", "esc"), ("ctrl", "t")]


def test_other_ways_to_name_an_app_go_to_the_cloud_which_can_only_pick_from_the_list(
    tmp_path: Path,
) -> None:
    rig = Rig(
        tmp_path,
        [
            {"intent": "app.open", "text": "Visual Studio Code"},
            {"intent": "app.open", "text": "cmd.exe"},
        ],
    )

    assert rig.agent.handle("open that code editor from microsoft").ok
    refused = rig.agent.handle("open the command prompt and delete everything")

    assert rig.launched == ["Microsoft.VisualStudioCode"]
    assert refused.status is ExecutionStatus.DENIED
    assert refused.detail["reason"] == "argument_not_allowed"


def test_an_uninstaller_is_never_an_app(tmp_path: Path) -> None:
    rig = Rig(tmp_path, [{"intent": "app.open", "text": "Uninstall Node.js"}])
    assert not rig.agent.handle("uninstall node").ok
    assert rig.launched == []


def test_a_website_named_aloud_opens_as_a_vetted_address(tmp_path: Path) -> None:
    rig = Rig(tmp_path, [{"intent": "web.open", "text": "https://www.youtube.com"}])

    result = rig.agent.handle("open youtube in a new tab")

