def test_an_exact_app_name_from_the_model_is_never_swapped_for_another(tmp_path: Path) -> None:
    from voice_agent.actions.apps import app_open_spec
    from voice_agent.engine.command_registry import CommandRegistry
    from voice_agent.nlu.alias_matcher import AliasMatcher

    registry = CommandRegistry()
    registry.register(app_open_spec({"The Sims": "id-the-sims", "Sims": "id-sims"}))
    matcher = AliasMatcher(registry)

    assert matcher.choice_for("app.open", "Sims") == "Sims"
    assert matcher.choice_for("app.open", "The Sims") == "The Sims"
