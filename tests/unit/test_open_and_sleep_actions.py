"""The executors for app.open, web.open and system.sleep, over fakes: nothing is launched,
opened or put to sleep."""

from __future__ import annotations

import pytest
from tests.conftest import RecordingKeySender

from voice_agent.actions.apps import AppActions, app_open_spec, launchable
from voice_agent.actions.power import PowerActions
from voice_agent.actions.web import WebActions, browser_in_front
from voice_agent.core.exceptions import ActionExecutionError
from voice_agent.core.models import CommandSpec, ExecutionStatus, ResolvedCommand, Risk

APPS = {"Google Chrome": "Chrome", "Visual Studio Code": "Microsoft.VisualStudioCode"}


def _command(intent: str, text: str | None = None) -> ResolvedCommand:
    return ResolvedCommand(spec=CommandSpec(intent=intent, risk=Risk.LOW), text=text)


def test_the_start_menu_list_drops_uninstallers_and_keeps_the_first_of_a_name() -> None:
    found = launchable(
        [
            ("Google Chrome", "Chrome"),
            ("Uninstall Node.js", "Microsoft.AutoGenerated.{BF60}"),
            ("Google Chrome", "Chrome.Other"),
            ("", "Nameless"),
            ("x" * 61, "TooLong"),
            ("Notepad", ""),
            ("Programm deinstallieren", "Microsoft.AutoGenerated.{AB12}"),
            ("Backup script", "C:/Tools/backup.BAT"),
            ("Node.js website", "https://nodejs.org/"),  # how Start lists a web shortcut
            ("Vendor website", "C:/ProgramData/Vendor/site.url"),
        ]
    )
    assert found == {"Google Chrome": "Chrome"}


def test_app_open_offers_exactly_the_apps_found() -> None:
    spec = app_open_spec(APPS)
    assert spec.text is not None
    assert spec.text.choices == ("Google Chrome", "Visual Studio Code")
    assert spec.permissions == ("app.launch",)


def test_an_app_is_launched_by_the_shell_id_listed_for_its_name() -> None:
    launched: list[str] = []
    result = AppActions(APPS, launched.append).execute(_command("app.open", "Visual Studio Code"))

    assert launched == ["Microsoft.VisualStudioCode"]
    assert result.ok and result.message == "Opening Visual Studio Code."


def test_a_name_not_in_the_list_launches_nothing() -> None:
    launched: list[str] = []
    with pytest.raises(ActionExecutionError):
        AppActions(APPS, launched.append).execute(_command("app.open", "cmd.exe /c del *"))
    assert launched == []


@pytest.mark.parametrize(
    ("program", "browser"),
    [
        (r"C:\Program Files\Google\Chrome\Application\chrome.exe", True),
        (r"C:\Program Files (x86)\Microsoft\Edge\Application\MSEDGE.EXE", True),
        (r"C:\Windows\explorer.exe", False),
        (r"C:\Users\me\AppData\Local\Programs\Microsoft VS Code\Code.exe", False),
        (None, False),
    ],
)
def test_a_new_tab_goes_to_the_browser_in_front(program: str | None, browser: bool) -> None:
    assert (browser_in_front(program) is not None) is browser


def test_only_a_vetted_https_address_is_opened() -> None:
    opened: list[str] = []
    actions = WebActions(opened.append)

    assert actions.execute(_command("web.open", "https://www.youtube.com/")).ok
    with pytest.raises(ActionExecutionError):
        actions.execute(_command("web.open", "file:///C:/"))
    assert opened == ["https://www.youtube.com/"]


def test_classic_sleep_needs_no_keys() -> None:
    keys = RecordingKeySender()
    result = PowerActions(keys, suspend=lambda: True, pause=lambda _s: None).execute(
        _command("system.sleep")
    )
    assert result.ok and keys.calls == []


def test_modern_standby_uses_the_windows_sleep_menu() -> None:
    keys, waits = RecordingKeySender(), []
    PowerActions(keys, suspend=lambda: False, pause=waits.append).execute(_command("system.sleep"))

    assert keys.calls == [("win", "x"), ("u",), ("s",)]
    assert all(wait < 1 for wait in waits)


def test_the_emergency_stop_between_steps_closes_the_menu_and_stops() -> None:
    keys = RecordingKeySender()
    checks = iter([False, True])  # stopped after the menu opened
    result = PowerActions(
        keys, suspend=lambda: False, pause=lambda _s: None, interrupted=lambda: next(checks)
    ).execute(_command("system.sleep"))

    assert result.status is ExecutionStatus.DENIED
    assert keys.calls == [("win", "x"), ("esc",)]  # never "u", never "s"
